"""W16-E2 original synthetic 12→24 fps image marker + 48k PCM decoded mux.

Not a C3 walking/voice source. All generated bytes are original and auditable,
explicit 12/1 -> 24/1 repeat; 48k sample-space clock, PTS observed in native file.
"""
import argparse,hashlib,json,math,struct,wave
from fractions import Fraction
from pathlib import Path
W,H=128,72
MOTION_FPS=12
VIDEO_FPS=24
AUDIO_RATE=48000
MOTION_FRAMES=24
VIDEO_FRAMES=48
PCM_SAMPLES=96000
RIGHTS="ORIGINAL_SELF_AUTHORED_SYNTHETIC"
def frame(index):
 if index not in range(VIDEO_FRAMES):raise ValueError("FRAME_OUTSIDE_EXACT_RANGE")
 src=index//2
 buf=bytearray(W*H*3)
 # Multi-color marker moves two pixels per source step, entirely source-authored.
 x=6+src*3
 y=12+(src%6)*5
 for row in range(y,y+14):
  for col in range(x,x+10):
   k=3*(row*W+col)
   buf[k:k+3]=bytes((240,40+(src%5)*24,35+(src%4)*45))
 # Distinct source-index bitfield on first scanline (not a visual model).
 for bit in range(5):
  c=255 if src>>bit&1 else 0
  for col in range(bit*5,bit*5+3):
   k=3*col;buf[k:k+3]=bytes((c,255-c,20))
 return bytes(buf)
def pcm():
 samples=[]
 for i in range(PCM_SAMPLES):
  event=i//4000
  phase=i%4000
  sample=0
  # Original non-speech synthetic 1ms click every exact 12fps source frame.
  if phase<48:
   sample=round(7500*(1-phase/48)*(1 if event%2==0 else -1))
  samples.append(int(sample))
 return struct.pack("<"+"h"*len(samples),*samples)
def make(folder,profile):
 if profile not in ("forward","outward"):raise ValueError("PROFILE")
 p=Path(folder);p.mkdir(parents=True,exist_ok=True)
 source_shas=[]
 for i in range(VIDEO_FRAMES):
  body=frame(i)
  path=p/("frame_%03d.ppm"%i)
  path.write_bytes(("P6\n%d %d\n255\n"%(W,H)).encode()+body)
  source_shas.append(hashlib.sha256(body).hexdigest())
 samples=pcm()
 with wave.open(str(p/"source_48k_mono.wav"),"wb") as w:
  w.setnchannels(1);w.setsampwidth(2);w.setframerate(AUDIO_RATE);w.writeframes(samples)
 receipt={
  "schema":"scp.walk_e2_original_decoded_av.v1",
  "source_rights":RIGHTS,"profile":profile,
  "video_frames":VIDEO_FRAMES,"source_motion_frames":MOTION_FRAMES,
  "video_rate":"24/1","source_motion_rate":"12/1","audio_rate":"48000/1",
  "pcm_sample_count":PCM_SAMPLES,"source_pcm_sha256":hashlib.sha256(samples).hexdigest(),
  "frame_rgb_sha256":source_shas,"source_motion_index_by_video_frame":[i//2 for i in range(VIDEO_FRAMES)],
  "clock_origin":"0/1","source_rights_scope":"UNRELATED_SELF_AUTHORED_AV_PROBE_NOT_C3_RIG_OR_R009",
  "expected_end_seconds":"2/1",
  "scope":"ACTUAL_MUX_DECODE_NUMERIC_ONLY_NOT_VOICE_LIPS_OR_CHARACTER_RENDER"}
 (p/"source_manifest.json").write_text(json.dumps(receipt,sort_keys=True,indent=2)+"\n")
 print("W16E2_SOURCE_ORIGINAL_PCM_AND_RGB_PASS",profile,hashlib.sha256(samples).hexdigest())
def main():
 a=argparse.ArgumentParser()
 a.add_argument("--out",required=True);a.add_argument("--profile",choices=("forward","outward"),required=True)
 v=a.parse_args();make(v.out,v.profile)
if __name__=="__main__":main()

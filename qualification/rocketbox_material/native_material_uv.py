"""Source-pinned Microsoft Rocketbox MIT native UV and color-material qualification.

The imported official 80-bone source meshes and material labels decide assignments.
No autogenerated head/body guesses; missing or ambiguous source names fail closed.
Artistic two-view source-only evidence, NOT realistic gait, biological contact, or product acceptance.
"""

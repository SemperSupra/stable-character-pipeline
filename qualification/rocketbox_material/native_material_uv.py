def sha256_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(data)
    return digest.hexdigest()


def git_blob_file(path):
    size = path.stat().st_size
    digest = hashlib.sha1()
    digest.update(("blob %d\0" % size).encode("ascii"))
    with path.open("rb") as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(data)
    return digest.hexdigest()


def classify_source_material(material_name, image_names):
    """Returns exact body/head/UNKNOWN, rejects contradictory source labels."""
    # Original FBX image paths contain a vendor directory named with_opacity_version
    # even for body/head maps; classify the ORIGINAL MATERIAL and image BASENAMES only.
    labels = [material_name, *(name.replace("\\\\", "/").rsplit("/", 1)[-1] for name in image_names)]
    parts = set()
    for label in labels:
        parts.update(p for p in re.split(r"[^a-z0-9]+", label.lower()) if p)
    found = set()
    if parts.intersection(("head", "face")):
        found.add("head")
    if parts.intersection(("body", "torso")):
        found.add("body")
    if "opacity" in parts:
        found.add("opacity")
    if len(found) != 1:
        return "UNKNOWN"
    return next(iter(found))


def validate_material_plan(rows):
    """Require real source-labeled polygons AND native UVs for both texture types."""
    result = {"body": 0, "head": 0, "opacity": 0}
    for row in rows:
        kind = row["classification"]
        count = row["polygons"]
        if isinstance(count, bool) or not isinstance(count, int) or count < 0:
            raise ValueError("INVALID_POLYGON_COUNT")
        if kind == "UNKNOWN" and count:
            raise ValueError("UNRESOLVED_MATERIAL_WITH_POLYGONS:" + row["material"])
        if kind in result:
            if not row.get("uv_present"):
                raise ValueError("MISSING_NATIVE_UV:" + row["material"])
            result[kind] += count
    if any(count == 0 for count in result.values()):
        raise ValueError("UNRESOLVED_BODY_HEAD_OPACITY_NATIVE_SLOT:" + json.dumps(result, sort_keys=True))
    return result


def write_receipt(out, receipt):
    out.mkdir(parents=True, exist_ok=True)
    (out / "native_material_uv_receipt.json").write_text(
        json.dumps(receipt, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
    )


def native_run(source_blend, textures_dir, out):
    import bpy
    from mathutils import Vector

    if not source_blend.is_file() or sha256_file(source_blend) != SOURCE_BLEND_SHA:
        raise RuntimeError("FROZEN_SOURCE_BLEND_SHA_MISMATCH")
    for filename, expected_blob in SOURCE_GIT_BLOBS.items():
        path = textures_dir / filename
        if not path.is_file() or path.is_symlink() or path.stat().st_size != SOURCE_TGA_BYTES[filename]:
            raise RuntimeError("MIT_ORIGINAL_TGA_BYTES_MISSING:" + filename)
        if git_blob_file(path) != expected_blob:
            raise RuntimeError("MIT_ORIGINAL_TGA_GIT_BLOB_MISMATCH:" + filename)

    bpy.ops.wm.open_mainfile(filepath=str(source_blend))
    scene = bpy.context.scene
    if scene.frame_end - scene.frame_start + 1 != 72 or scene.render.fps != 12:
        raise RuntimeError("SOURCE_SCENE_CLOCK_MISMATCH")
    if bpy.data.objects.get("SourceProbeGround") is None:
        raise RuntimeError("SOURCE_GROUND_MISSING")

    images = {filename: bpy.data.images.load(str(textures_dir / filename), check_existing=False)
              for filename in SOURCE_GIT_BLOBS}
    for image in images.values():
        image.colorspace_settings.name = "sRGB"
    receipt = {
        "schema": SCHEMA,
        "source_repo": "microsoft/Microsoft-Rocketbox",
        "source_commit": SOURCE_COMMIT,
        "license": "MIT_WITH_ORIGINAL_COPYRIGHT_NOTICE",
        "source_blend_sha256": SOURCE_BLEND_SHA,
        "textures": {name: {"source_git_blob_sha1": SOURCE_GIT_BLOBS[name],
                            "sha256": sha256_file(textures_dir / name),
                            "width": images[name].size[0],
                            "height": images[name].size[1]} for name in images},
        "actors": {},
        "views": [],
        "uv_assignment": "UNKNOWN",
        "artistic_color_render": "NOT_RUN",
        "human_realism": "UNKNOWN",
        "physical_contact": "UNKNOWN",
        "biological_gait": "UNKNOWN",
        "product_accepted": False,
    }
    for actor in ACTORS:
        root = bpy.data.objects.get(actor)
        if root is None:
            raise RuntimeError("SOURCE_ACTOR_MISSING:" + actor)
        arms = [ob for ob in bpy.data.objects if ob.type == "ARMATURE" and
                (ob.parent == root or (ob.parent and ob.parent.parent == root))]
        if len(arms) != 1 or len(arms[0].data.bones) != 80:
            raise RuntimeError("SOURCE_80BONE_RIG_MISMATCH:" + actor)
        arm = arms[0]
        meshes = [ob for ob in bpy.data.objects if ob.type == "MESH" and
                  (ob.parent == arm or any(m.type == "ARMATURE" and m.object == arm
                                           for m in ob.modifiers))]
        if not meshes:
            raise RuntimeError("SOURCE_SKINNED_MESH_MISSING:" + actor)

        pending = []
        rows = []
        for mesh in meshes:
            if not mesh.data.uv_layers or not mesh.data.loops or not mesh.data.polygons:
                raise RuntimeError("SOURCE_MESH_WITHOUT_UV_OR_POLYGONS:" + mesh.name)
            uv_layer = mesh.data.uv_layers.active or mesh.data.uv_layers[0]
            uv_values = [float(c) for item in uv_layer.data for c in item.uv]
            if not uv_values or not all(math.isfinite(v) for v in uv_values):
                raise RuntimeError("SOURCE_UV_NONFINITE:" + mesh.name)
            for slot_index, slot in enumerate(mesh.material_slots):
                material = slot.material
                assigned = sum(1 for poly in mesh.data.polygons if poly.material_index == slot_index)
                names = []
                if material and material.use_nodes and material.node_tree:
                    for node in material.node_tree.nodes:
                        if node.type == "TEX_IMAGE" and node.image is not None:
                            names.append(node.image.name)
                            names.append(node.image.filepath)
                kind = classify_source_material(material.name if material else "", names)
                rows.append({
                    "mesh": mesh.name, "material": material.name if material else "(NONE)",
                    "source_image_labels": names, "classification": kind,
                    "polygons": assigned, "uv_present": bool(uv_values),
                    "uv_sampled_values": len(uv_values),
                    "uv_range": [min(uv_values), max(uv_values)],
                })
                if assigned and kind != "UNKNOWN":
                    pending.append((mesh, slot_index, material, kind))
        receipt["actors"][actor] = {
            "armature": arm.name, "bones": len(arm.data.bones),
            "source_meshes": len(meshes), "source_vertices": sum(len(m.data.vertices) for m in meshes),
            "native_material_slots": rows,
        }
        write_receipt(out, receipt)
        try:
            coverage = validate_material_plan(rows)
        except ValueError as exc:
            receipt["actors"][actor]["status"] = "SOURCE_MATERIAL_IDENTITY_UNRESOLVED"
            write_receipt(out, receipt)
            raise RuntimeError("SOURCE_MATERIAL_IDENTITY_UNRESOLVED:" + actor + ":" + str(exc))
        for mesh, slot_index, material, kind in pending:
            new_material = material.copy()
            new_material.name = actor + "_" + kind + "_ORIGINAL_MIT_COLOR"
            new_material.use_nodes = True
            nodes = new_material.node_tree.nodes
            nodes.clear()
            output = nodes.new("ShaderNodeOutputMaterial")
            bsdf = nodes.new("ShaderNodeBsdfPrincipled")
            texture = nodes.new("ShaderNodeTexImage")
            texture.image = images[TEXTURES[actor][kind]]
            new_material.node_tree.links.new(texture.outputs["Color"], bsdf.inputs["Base Color"])
            if kind == "opacity":
                # Original 32-bit TGA alpha controls native eyebrow/hair transparency.
                new_material.node_tree.links.new(texture.outputs["Alpha"], bsdf.inputs["Alpha"])
            new_material.node_tree.links.new(bsdf.outputs["BSDF"], output.inputs["Surface"])
            bsdf.inputs["Roughness"].default_value = 0.78
            mesh.material_slots[slot_index].material = new_material
        receipt["actors"][actor]["status"] = "SOURCE_LABELED_ORIGINAL_UV_TEXTURES_BOUND"
        receipt["actors"][actor]["source_polygon_coverage"] = coverage

    receipt["uv_assignment"] = "SOURCE_LABELED_MIT_BODY_HEAD_OPACITY_BINDING_VERIFIED"
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 8
    scene.render.resolution_x = 640
    scene.render.resolution_y = 360
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = "PNG"
    if scene.world is None:
        scene.world = bpy.data.worlds.new("MITColorProbeWorld")
    scene.world.use_nodes = True
    world_bg = scene.world.node_tree.nodes.get("Background")
    if world_bg is not None:
        world_bg.inputs["Color"].default_value = (0.65, 0.7, 0.75, 1)
        world_bg.inputs["Strength"].default_value = 0.8
    for label, location, energy in (
        ("Key", (1.5, -4, 5), 1250),
        ("Fill", (-3, 1, 4), 950),
    ):
        lamp = bpy.data.lights.new("MITOriginal_" + label, type="AREA")
        lamp.energy = energy
        lamp.shape = "DISK"
        lamp.size = 5
        ob = bpy.data.objects.new("MITOriginal_" + label, lamp)
        scene.collection.objects.link(ob)
        ob.location = location
        ob.rotation_euler = (Vector((0, 0, 1)) - ob.location).to_track_quat("-Z", "Y").to_euler()
    if scene.camera is None:
        raise RuntimeError("FROZEN_NATIVE_CAMERA_MISSING")
    for name, location, frame in (
        ("front_000", (0, -10, 2.2), 0),
        ("front_036", (0, -10, 2.2), 36),
        ("oblique_000", (3, -9, 3), 0),
        ("oblique_036", (3, -9, 3), 36),
    ):
        scene.frame_set(frame)
        scene.camera.location = location
        scene.camera.rotation_euler = (Vector((0, 0, 1.1)) - scene.camera.location).to_track_quat("-Z", "Y").to_euler()
        scene.render.filepath = str(out / (name + ".png"))
        bpy.ops.render.render(write_still=True)
        image_bytes = (out / (name + ".png")).read_bytes()
        if not image_bytes.startswith(b"\x89PNG\r\n\x1a\n"):
            raise RuntimeError("NATIVE_PNG_SIGNATURE_MISMATCH:" + name)
        receipt["views"].append({"view": name, "frame": frame,
                                 "png_sha256": hashlib.sha256(image_bytes).hexdigest(),
                                 "png_bytes": len(image_bytes)})
        write_receipt(out, receipt)
    receipt["artistic_color_render"] = "FOUR_NATIVE_CPU_SOURCE_FRAMES_RENDERED"
    write_receipt(out, receipt)
    print(json.dumps({"status": receipt["artistic_color_render"],
                      "uv_assignment": receipt["uv_assignment"],
                      "views": len(receipt["views"]), "product_accepted": False}))


if __name__ == "__main__":
    if "--" not in sys.argv:
        raise RuntimeError("ARGS_REQUIRED")
    argv = sys.argv[sys.argv.index("--") + 1:]
    if len(argv) != 3:
        raise RuntimeError("USAGE: source.blend pinned_color_dir output_dir")
    native_run(*(Path(arg).resolve() for arg in argv))
